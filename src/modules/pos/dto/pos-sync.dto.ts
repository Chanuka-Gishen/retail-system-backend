import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import {
  ArrayMinSize,
  IsArray,
  IsEnum,
  IsIn,
  IsNotEmpty,
  IsNumber,
  IsOptional,
  IsString,
  IsUUID,
  Min,
  ValidateNested,
} from 'class-validator';
import { Type, Transform } from 'class-transformer';
import { TenderType } from '@prisma/client';

export class OfflineSaleItemSyncDto {
  @ApiProperty({ description: 'Product variant UUID' })
  @IsUUID('4')
  @IsNotEmpty()
  variantId!: string;

  @ApiProperty({ example: 2.0, description: 'Sold quantity' })
  @IsNumber({ maxDecimalPlaces: 3 })
  @Min(0.001)
  quantity!: number;

  @ApiPropertyOptional({ example: 750.0, description: 'Sold unit price' })
  @IsOptional()
  @IsNumber({ maxDecimalPlaces: 2 })
  @Min(0)
  unitPrice?: number;

  @ApiPropertyOptional({ example: 0, description: 'Discount applied to item' })
  @IsOptional()
  @IsNumber({ maxDecimalPlaces: 2 })
  @Min(0)
  discountAmount?: number = 0;
}

export class OfflinePaymentSyncDto {
  @ApiProperty({ enum: TenderType, example: TenderType.CASH })
  @IsEnum(TenderType)
  @IsNotEmpty()
  tenderType!: TenderType;

  @ApiProperty({ example: 1500.0, description: 'Amount paid' })
  @IsNumber({ maxDecimalPlaces: 2 })
  @Min(0.01)
  amount!: number;

  @ApiPropertyOptional({ example: 'AUTH-OFFLINE-7892', description: 'Slip reference / card transaction ID' })
  @IsOptional()
  @IsString()
  referenceNumber?: string;
}

export class OfflineSaleSyncDto {
  @ApiProperty({
    example: 'op-term01-d89f2a24-1182-41d3',
    description: 'Unique client operation UUID generated by offline Dexie IndexedDB',
  })
  @IsString()
  @IsNotEmpty()
  clientOperationId!: string;

  @ApiPropertyOptional({ description: 'Branch UUID where offline sale was made' })
  @IsOptional()
  @Transform(({ value }) => (!value || value === '' || value === '00000000-0000-0000-0000-000000000000' ? undefined : value))
  @IsUUID('4')
  branchId?: string;

  @ApiPropertyOptional({ description: 'Warehouse UUID' })
  @IsOptional()
  @Transform(({ value }) => (!value || value === '' ? undefined : value))
  @IsUUID('4')
  warehouseId?: string;

  @ApiPropertyOptional({ description: 'POS Terminal UUID' })
  @IsOptional()
  @Transform(({ value }) => (!value || value === '' ? undefined : value))
  @IsUUID('4')
  posTerminalId?: string;

  @ApiPropertyOptional({ description: 'Cash Drawer Session UUID' })
  @IsOptional()
  @Transform(({ value }) => (!value || value === '' ? undefined : value))
  @IsUUID('4')
  cashSessionId?: string;

  @ApiPropertyOptional({ description: 'Customer UUID' })
  @IsOptional()
  @Transform(({ value }) => (!value || value === '' ? undefined : value))
  @IsUUID('4')
  customerId?: string;

  @ApiPropertyOptional({ example: 'INV-OFFLINE-00109' })
  @IsOptional()
  @IsString()
  offlineInvoiceNumber?: string;

  @ApiProperty({ example: '2026-11-09T14:30:00.000Z', description: 'When the offline sale took place' })
  @IsString()
  @IsNotEmpty()
  completedAt!: string;

  @ApiPropertyOptional({ example: 0, default: 0 })
  @IsOptional()
  @IsNumber({ maxDecimalPlaces: 2 })
  @Min(0)
  cartDiscountAmount?: number = 0;

  @ApiProperty({ type: [OfflineSaleItemSyncDto] })
  @IsArray()
  @ArrayMinSize(1)
  @ValidateNested({ each: true })
  @Type(() => OfflineSaleItemSyncDto)
  items!: OfflineSaleItemSyncDto[];

  @ApiProperty({ type: [OfflinePaymentSyncDto] })
  @IsArray()
  @ArrayMinSize(1)
  @ValidateNested({ each: true })
  @Type(() => OfflinePaymentSyncDto)
  payments!: OfflinePaymentSyncDto[];
}

export class OfflineCashTransactionSyncDto {
  @ApiProperty({ example: 'op-cash-112233', description: 'Unique operation ID' })
  @IsString()
  @IsNotEmpty()
  clientOperationId!: string;

  @ApiProperty({ description: 'Cash Drawer Session UUID' })
  @IsUUID('4')
  @IsNotEmpty()
  sessionId!: string;

  @ApiProperty({ enum: ['CASH_IN', 'CASH_OUT'], example: 'CASH_IN' })
  @IsIn(['CASH_IN', 'CASH_OUT'])
  type!: 'CASH_IN' | 'CASH_OUT';

  @ApiProperty({ example: 2500.0, description: 'Amount' })
  @IsNumber({ maxDecimalPlaces: 2 })
  @Min(0.01)
  amount!: number;

  @ApiProperty({ example: 'Mid-shift float top-up while offline' })
  @IsString()
  @IsNotEmpty()
  reason!: string;

  @ApiPropertyOptional({ example: '2026-11-09T14:45:00.000Z' })
  @IsOptional()
  @IsString()
  occurredAt?: string;
}

export class BatchSyncDto {
  @ApiPropertyOptional({ type: [OfflineSaleSyncDto], description: 'List of sales recorded offline' })
  @IsOptional()
  @IsArray()
  @ValidateNested({ each: true })
  @Type(() => OfflineSaleSyncDto)
  sales?: OfflineSaleSyncDto[];

  @ApiPropertyOptional({
    type: [OfflineCashTransactionSyncDto],
    description: 'List of cash drawer movements recorded offline',
  })
  @IsOptional()
  @IsArray()
  @ValidateNested({ each: true })
  @Type(() => OfflineCashTransactionSyncDto)
  cashTransactions?: OfflineCashTransactionSyncDto[];
}

export class CatalogDeltaQueryDto {
  @ApiPropertyOptional({
    example: '2026-11-09T00:00:00.000Z',
    description: 'Client cache watermark timestamp (returns items modified since this date)',
  })
  @IsOptional()
  @Transform(({ value }) => (!value || value === '' ? undefined : value))
  @IsString()
  since?: string;

  @ApiPropertyOptional({ description: 'Branch UUID to filter branch specific catalog if applicable' })
  @IsOptional()
  @Transform(({ value }) => (!value || value === '' || value === '00000000-0000-0000-0000-000000000000' ? undefined : value))
  @IsUUID('4')
  branchId?: string;
}
